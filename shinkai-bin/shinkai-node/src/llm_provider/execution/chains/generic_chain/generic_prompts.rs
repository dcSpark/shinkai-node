impl JobPromptGenerator {
    /// A basic generic prompt generator
    /// summary_text is the content generated by an LLM on parsing (if exist)
    #[allow(clippy::too_many_arguments)]
    pub async fn generic_inference_prompt(
        db: Arc<SqliteManager>,
        custom_system_prompt: Option<String>,
        custom_user_prompt: Option<String>,
        user_message: String,
        image_files: HashMap<String, String>,
        video_files: HashMap<String, String>,
        audio_files: HashMap<String, String>,
        ret_nodes: ShinkaiFileChunkCollection,
        _summary_text: Option<String>,
        job_step_history: Option<Vec<ShinkaiMessage>>,
        tools: Vec<ShinkaiTool>,
        function_calls: Option<Vec<ToolCallFunctionResponse>>,
        job_id: String,
        additional_files: Vec<String>,
    ) -> Prompt {
        let mut prompt = Prompt::new();

        // Add system prompt
        let system_prompt = custom_system_prompt
        .filter(|p| !p.trim().is_empty())
        .unwrap_or_else(|| "You are a very helpful assistant. You may be provided with documents or content to analyze and answer questions about them, in that case refer to the content provided in the user message for your responses.".to_string());

        prompt.add_content(system_prompt, SubPromptType::System, 98);

        let has_ret_nodes = !ret_nodes.is_empty();

        // Add previous messages
        if let Some(step_history) = job_step_history {
            prompt.add_step_history(step_history, 97);
        }

        // Add tools if any. Decrease priority every 2 tools
        if !tools.is_empty() {
            let mut priority = 98;
            for (i, tool) in tools.iter().enumerate() {
                if let Ok(tool_content) = tool.json_function_call_format() {
                    match tool_content.get("function") {
                        Some(function) => {
                            let tool_router_key = function["tool_router_key"].as_str().unwrap_or("");
                            if tool_router_key == "local:::__official_shinkai:::shinkai_sqlite_query_executor" {
                                let job_id_clone = job_id.clone();
                                if let Ok(current_tables) = get_current_tables(job_id_clone).await {
                                    if !current_tables.is_empty() {
                                        prompt.add_content(
                                            format!(
                                                "<current_tables>\n{}\n</current_tables>\n",
                                                current_tables.join("; \n")
                                            ),
                                            SubPromptType::ExtraContext,
                                            97,
                                        );
                                    }
                                }
                            }
                            // Skip adding TypeScript unsafe processor tool
                            // This tool is not supported in Gemini due to undefined function parameters Object
                            if tool_router_key == "local:::__official_shinkai:::shinkai_typescript_unsafe_processor" {
                                continue;
                            }
                        }
                        None => {}
                    }

                    prompt.add_tool(tool_content, SubPromptType::AvailableTool, priority);
                }
                if (i + 1) % 2 == 0 {
                    priority = priority.saturating_sub(1);
                }
            }
            let mut all_files = vec![];
            // Add job scope files
            let job_scope = ShinkaiFileManager::get_absolute_path_for_job_scope(&db, &job_id);
            if let Ok(job_scope) = job_scope {
                all_files.extend(job_scope);
            }
            // Add fs files and Agent files, ensuring no duplicates
            let mut unique_files: HashSet<String> = all_files.into_iter().collect();
            unique_files.extend(additional_files.into_iter());
            all_files = unique_files.into_iter().collect();

            if !all_files.is_empty() {
                prompt.add_content(
                    format!("<current_files>\n{}\n</current_files>\n", all_files.join("\n")),
                    SubPromptType::ExtraContext,
                    97,
                );
            }
        }

        // Parses the retrieved nodes as individual sub-prompts, to support priority pruning
        // and also grouping i.e. instead of having 100 tiny messages, we have a message with the chunks grouped
        {
            if has_ret_nodes && !user_message.is_empty() {
                prompt.add_content("--- start --- \n".to_string(), SubPromptType::ExtraContext, 97);
            }

            prompt.add_ret_node_content(ret_nodes, SubPromptType::ExtraContext, 96);

            if has_ret_nodes && !user_message.is_empty() {
                prompt.add_content("--- end ---".to_string(), SubPromptType::ExtraContext, 97);
            }
        }

        // Add the user question and the preference prompt for the answer
        if !user_message.is_empty() {
            let mut content = user_message.clone();

            // If a custom user prompt is provided, use it as a template
            if let Some(template) = custom_user_prompt {
                let mut template_content = template.clone();

                // Insert user_message into the template
                if !template_content.contains("{{user_message}}") {
                    template_content.push_str(&format!("\n{}", user_message));
                } else {
                    template_content = template_content.replace("{{user_message}}", &user_message);
                }

                content = template_content;
            }

            // Combine all media files (images, videos, audio) into a single HashMap
            let mut media_files = HashMap::new();
            media_files.extend(image_files);
            media_files.extend(video_files);
            media_files.extend(audio_files);

            prompt.add_omni(content, media_files, SubPromptType::UserLastMessage, 100);
        }

        // Process function calls and their responses if they exist
        if let Some(function_calls) = function_calls {
            append_tool_history(&mut prompt, function_calls);
        }

        // eprintln!("prompt after adding function call: {:?}", prompt);
        prompt
    }
}

// The tag is optional metadata, so stored calls from older node versions still load.
// Untagged records keep their original order because their turn boundaries are unknown.
pub(super) fn tag_inference_turn(
    calls: &mut [crate::llm_provider::execution::chains::inference_chain_trait::FunctionCall],
) {
    let turn = uuid::Uuid::new_v4().to_string();
    for call in calls {
        let metadata = call.provider_metadata.get_or_insert_with(|| json!({}));
        if let Some(metadata) = metadata.as_object_mut() {
            metadata.insert("inference_turn_id".into(), json!(turn));
        }
    }
}

fn append_tool_history(prompt: &mut Prompt, calls: Vec<ToolCallFunctionResponse>) {
    let mut remaining = calls.as_slice();
    while let Some(first) = remaining.first() {
        let turn = first
            .function_call
            .provider_metadata
            .as_ref()
            .and_then(|value| value["inference_turn_id"].as_str());
        let count = if let Some(turn) = turn {
            remaining
                .iter()
                .take_while(|call| {
                    call.function_call
                        .provider_metadata
                        .as_ref()
                        .and_then(|value| value["inference_turn_id"].as_str())
                        == Some(turn)
                })
                .count()
        } else {
            1
        };
        let (group, rest) = remaining.split_at(count);
        for call in group {
            prompt.add_function_call(
                json!({
                    "provider_metadata": call.function_call.provider_metadata,
                    "name": call.function_call.name,
                    "call_id": call.function_call.id,
                    "arguments": call.function_call.arguments
                }),
                100,
            );
        }
        for call in group {
            prompt.add_function_call_response(serde_json::to_value(call).unwrap(), 100);
        }
        remaining = rest;
    }
}

#[cfg(test)]
mod tool_turn_tests {
    use super::*;
    use crate::llm_provider::execution::chains::inference_chain_trait::FunctionCall;

    fn call(name: &str) -> FunctionCall {
        FunctionCall {
            provider_metadata: None,
            name: name.into(),
            arguments: Default::default(),
            tool_router_key: None,
            response: None,
            index: 0,
            id: Some(name.into()),
            call_type: Some("function".into()),
        }
    }

    #[test]
    fn parallel_history_keeps_inference_turn_boundaries_and_native_data() {
        let native = json!({"claude_content": [{"type": "thinking", "signature": "signed"}]});
        let mut first = vec![call("A"), call("B")];
        first[0].provider_metadata = Some(native.clone());
        first[1].provider_metadata = Some(native.clone());
        tag_inference_turn(&mut first);
        let mut second = vec![call("C")];
        tag_inference_turn(&mut second);
        assert_ne!(first[0].provider_metadata, second[0].provider_metadata);
        let responses = first
            .into_iter()
            .chain(second)
            .map(|function_call| ToolCallFunctionResponse {
                response: format!("result {}", function_call.name),
                function_call,
            })
            .collect::<Vec<_>>();
        // Exercise stored-history loading, as well as live inference history.
        let saved = serde_json::to_string(&responses).unwrap();
        let mut prompt = Prompt::new();
        append_tool_history(&mut prompt, serde_json::from_str(&saved).unwrap());
        let (messages, _) = prompt.generate_chat_completion_messages(None, &|_| 0);
        assert_eq!(
            messages.iter().map(|m| m.role.as_deref().unwrap()).collect::<Vec<_>>(),
            [
                "assistant",
                "assistant",
                "function",
                "function",
                "assistant",
                "function"
            ]
        );
        assert_eq!(messages[0].function_call.as_ref().unwrap().name, "A");
        assert_eq!(messages[1].function_call.as_ref().unwrap().name, "B");
        assert_eq!(messages[4].function_call.as_ref().unwrap().name, "C");
        for message in &messages[..2] {
            assert_eq!(
                message
                    .function_call
                    .as_ref()
                    .unwrap()
                    .provider_metadata
                    .as_ref()
                    .unwrap()["claude_content"],
                native["claude_content"]
            );
        }
    }

    #[test]
    fn parallel_generic_history_becomes_one_assistant_call_turn() {
        let mut first = vec![call("A"), call("B")];
        tag_inference_turn(&mut first);
        let mut later = vec![call("C")];
        tag_inference_turn(&mut later);
        let responses = first
            .into_iter()
            .chain(later)
            .map(|function_call| ToolCallFunctionResponse {
                response: "done".into(),
                function_call,
            })
            .collect();
        let mut prompt = Prompt::new();
        append_tool_history(&mut prompt, responses);
        let model = shinkai_message_primitives::schemas::llm_providers::serialized_llm_provider::LLMProviderInterface::OpenAILegacy(
            shinkai_message_primitives::schemas::llm_providers::serialized_llm_provider::OpenAILegacy {
                model_type: "gpt-4o".into()
            });
        let result =
            crate::llm_provider::providers::shared::openai_api::openai_prepare_messages(&model, prompt).unwrap();
        let crate::managers::model_capabilities_manager::PromptResultEnum::Value(messages) = result.messages else {
            panic!("expected messages")
        };
        let messages = messages.as_array().unwrap();
        assert_eq!(messages.len(), 5);
        assert_eq!(messages[0]["tool_calls"].as_array().unwrap().len(), 2);
        assert_eq!(messages[0]["tool_calls"][0]["id"], "A");
        assert_eq!(messages[0]["tool_calls"][1]["id"], "B");
        assert_eq!(messages[1]["tool_call_id"], "A");
        assert_eq!(messages[2]["tool_call_id"], "B");
        assert_eq!(messages[3]["tool_calls"][0]["id"], "C");
        assert_eq!(messages[4]["tool_call_id"], "C");
        assert!(messages[0]["tool_calls"][0]["function"]
            .get("provider_metadata")
            .is_none());
    }

    #[test]
    fn old_untagged_history_keeps_its_order() {
        let calls = [call("A"), call("B")]
            .into_iter()
            .map(|function_call| ToolCallFunctionResponse {
                response: "old result".into(),
                function_call,
            })
            .collect();
        let mut prompt = Prompt::new();
        append_tool_history(&mut prompt, calls);
        let (messages, _) = prompt.generate_chat_completion_messages(None, &|_| 0);
        assert_eq!(
            messages.iter().map(|m| m.role.as_deref().unwrap()).collect::<Vec<_>>(),
            ["assistant", "function", "assistant", "function"]
        );
    }
}
